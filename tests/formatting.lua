-- Run: nvim --clean --headless -l tests/formatting.lua
vim.opt.runtimepath:append(vim.fn.expand("~/.local/share/nvim/lazy/conform.nvim"))
dofile("nvim/lua/johan/plugins/formatting.lua").config()
local conform = require("conform")
local directory = vim.fn.tempname()
local function write(path, contents)
  vim.fn.mkdir(vim.fs.dirname(path), "p")
  vim.fn.writefile(contents or {}, path)
end
local function check(path, expected)
  local buffer = vim.fn.bufadd(path)
  vim.bo[buffer].filetype = "typescript"
  assert(vim.deep_equal(conform.list_formatters_for_buffer(buffer), { expected }), path)
end
local ok, err = pcall(function()
  write(directory .. "/first/.git/HEAD")
  write(directory .. "/first/biome.json", { "{}" })
  write(directory .. "/second/.git/HEAD")
  write(directory .. "/third/.git/HEAD")
  write(directory .. "/third/biome.jsonc", { "{}" })
  vim.fn.mkdir(directory .. "/first/src", "p")
  vim.fn.mkdir(directory .. "/third/src", "p")
  vim.cmd.cd(directory .. "/first")
  check(directory .. "/first/src/example.ts", "biome")
  check(directory .. "/second/example.ts", "prettier")
  check(directory .. "/third/src/example.ts", "biome")
  vim.cmd.cd(directory .. "/second")
  check(directory .. "/first/src/example.ts", "biome")
  write(directory .. "/biome.json", { "{}" })
  check(directory .. "/second/example.ts", "prettier")
  write(directory .. "/second/biome.jsonc", { "{}" })
  check(directory .. "/second/example.ts", "biome")
  vim.fn.delete(directory .. "/second/biome.jsonc")
  check(directory .. "/second/example.ts", "prettier")
  local unnamed = vim.api.nvim_create_buf(false, true)
  vim.bo[unnamed].filetype = "typescript"
  assert(vim.deep_equal(conform.list_formatters_for_buffer(unnamed), { "prettier" }))
end)
vim.cmd.cd("/")
vim.fn.delete(directory, "rf")
if not ok then
  error(err)
end
print("Formatter selection: all checks passed")
